import Resolver from '@forge/resolver';
import {Application,type ActorContext} from './services/application';
import {forgeStore} from './storage/forge';
import {jiraGateway} from './integrations/jira';
import {withPrivacyMutationLock} from './privacy';
const app=new Application(forgeStore,jiraGateway,undefined,undefined,withPrivacyMutationLock);
const resolver=new Resolver();
resolver.define('bootstrap',({context})=>app.bootstrap(context as ActorContext));
resolver.define('seed',({context})=>app.seed(context as ActorContext));
resolver.define('importDataset',({context,payload})=>app.importDataset(context as ActorContext,payload));
resolver.define('saveDrill',({context,payload})=>app.saveDrill(context as ActorContext,payload));
resolver.define('listProjects',({context})=>app.listProjects(context as ActorContext));
resolver.define('issueTypes',({context,payload})=>app.issueTypes(context as ActorContext,payload));
resolver.define('previewActions',({context,payload})=>app.previewActions(context as ActorContext,payload));
resolver.define('createActions',({context,payload})=>app.createActions(context as ActorContext,payload));
resolver.define('deleteData',({context,payload})=>app.deleteData(context as ActorContext,payload));
resolver.define('reconcileAction',({context,payload})=>app.reconcileAction(context as ActorContext,payload));
resolver.define('recoverProjectLock',({context,payload})=>app.recoverProjectLock(context as ActorContext,payload));
export const handler=resolver.getDefinitions();
